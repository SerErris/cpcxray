"""Generate src/cpcxray/debugger/variable_tables.py: firmware and AMSDOS variables per machine.

Source: docs/memory.md (compiled from Taylor/Defoe, Bread80, CPCWiki and the ROMs; see there).
Section 1 holds the firmware variables with one column per machine, sections 2 and 3 the
AMSDOS variables (the same on every machine; section 3 relative to the workspace base &A700).

A row of size "area" names the variables of one firmware pack. Its size is computed per machine:
it reaches to the end of the last variable before the next area, so bytes without a known
meaning still resolve to the pack.

Usage (from the project root): python -m tools.extract_memory_variables
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import NamedTuple

from tools.extract_firmware_symbols import table_rows

ROOT = Path(__file__).resolve().parents[1]
MEMORY_DOC = ROOT / "docs" / "memory.md"
OUTPUT = ROOT / "src" / "cpcxray" / "debugger" / "variable_tables.py"
MODELS = ("464", "664", "6128")
AREA = "area"
AMSDOS_WORKSPACE_BASE = 0xA700  # the base section 3 is written for


class Variable(NamedTuple):
    """A variable before rendering.

    Attributes:
        address: Address on its machine.
        size: Size in bytes, or None for an area (computed from the variables after it).
        label: Label, e.g. TXT_CURSOR_ROW.
        description: What it holds.
        area: The row names a pack's area, not a variable.
    """

    address: int
    size: int | None
    label: str
    description: str
    area: bool = False


def parse_address(cell: str) -> int | None:
    """Turn "#B8D9" into &B8D9 and "-" into None."""
    return None if cell == "-" else int(cell.lstrip("#"), 16)


def parse_size(cell: str, model: str) -> int | None:
    """Turn "14", "14/15" (664/6128 / 464) or "area" (None) into the size on `model`."""
    if cell == AREA:
        return None
    sizes = cell.split("/")
    return int(sizes[1] if model == "464" and len(sizes) > 1 else sizes[0])


def with_area_sizes(variables: list[Variable]) -> list[Variable]:
    """Give each area the size up to the end of the last variable before the next area."""
    result = []
    for index, variable in enumerate(variables):
        if variable.size is None:
            end = variable.address
            for following in variables[index + 1 :]:
                if following.size is None:
                    break
                end = max(end, following.address + following.size)
            variable = variable._replace(size=end - variable.address, area=True)
        result.append(variable)
    return result


def firmware_variables(text: str) -> dict[str, list[Variable]]:
    """Section 1: per machine, its firmware variables in table order."""
    rows = table_rows(text, "## 1. Firmware variables")
    per_model = {}
    for model in MODELS:
        variables = [
            Variable(address, parse_size(row["Size"], model), row["Label"], row["Description"])
            for row in rows
            if (address := parse_address(row[model])) is not None
        ]
        per_model[model] = with_area_sizes(variables)
    return per_model


def amsdos_variables(text: str, heading: str, address_column: str) -> list[Variable]:
    """Section 2 or 3: the AMSDOS variables (the same on every machine)."""
    variables = [
        Variable(int(row[address_column].lstrip("#"), 16), parse_size(row["Size"], "6128"),
                 row["Label"], row["Description"])
        for row in table_rows(text, heading)
    ]  # fmt: skip
    return with_area_sizes(variables)


def render_table(name: str, variables: list[Variable]) -> list[str]:
    """Render one tuple of VariableEntry, sorted by address (areas before their contents)."""
    lines = [f"{name}: tuple[VariableEntry, ...] = ("]
    for variable in sorted(variables, key=lambda v: (v.address, -(v.size or 0))):
        area = ", area=True" if variable.area else ""
        lines.append(f"    VariableEntry(0x{variable.address:04X}, {variable.size}, "
                     f"{variable.label!r}, {variable.description!r}{area}),")  # fmt: skip
    return [*lines, ")", "", ""]


def render(per_model: dict[str, list[Variable]], fixed: list[Variable],
           workspace: list[Variable]) -> str:  # fmt: skip
    """Render the data module."""
    lines = [
        '"""CPC firmware and AMSDOS variables per machine (FR-DBG-11), generated - do not edit.',
        "",
        "Generated by tools/extract_memory_variables.py from docs/memory.md. Areas (one per",
        "firmware pack) cover the variables of the pack and the bytes between them.",
        "AMSDOS_WORKSPACE holds the addresses for the usual base &A700; the debugger moves them",
        "to the actual base (AMSDOS_MEMORY_POOL).",
        '"""',
        "",
        "# pylint: disable=too-many-lines  # generated data: one line per variable and machine",
        "",
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class VariableEntry(NamedTuple):",
        '    """One RAM variable.',
        "",
        "    Attributes:",
        "        address: First byte.",
        "        size: Size in bytes.",
        "        label: Label used in listings, e.g. TXT_CURSOR_ROW.",
        "        description: What it holds.",
        "        area: A pack's area (covers its variables and the bytes between them).",
        '    """',
        "",
        "    address: int",
        "    size: int",
        "    label: str",
        "    description: str",
        "    area: bool = False",
        "",
        "",
        f"AMSDOS_WORKSPACE_BASE = 0x{AMSDOS_WORKSPACE_BASE:04X}  # the base of AMSDOS_WORKSPACE",
        "",
    ]
    for model in MODELS:
        lines += render_table(f"OS_VARIABLES_{model}", per_model[model])
    lines += render_table("AMSDOS_FIXED", fixed)
    lines += render_table("AMSDOS_WORKSPACE", workspace)
    lines += [
        "OS_VARIABLES_BY_MODEL: dict[str, tuple[VariableEntry, ...]] = {",
        '    "464": OS_VARIABLES_464,',
        '    "664": OS_VARIABLES_664,',
        '    "6128": OS_VARIABLES_6128,',
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Extract the variables and write the data module."""
    text = MEMORY_DOC.read_text(encoding="utf-8")
    per_model = firmware_variables(text)
    fixed = amsdos_variables(text, "## 2. AMSDOS, fixed block", "Address")
    workspace = amsdos_variables(text, "## 3. AMSDOS workspace", "Address (base #A700)")
    OUTPUT.write_text(render(per_model, fixed, workspace), encoding="utf-8")
    counts = ", ".join(f"{model}: {len(variables)}" for model, variables in per_model.items())
    print(f"written to {OUTPUT} ({counts}; AMSDOS {len(fixed)} + {len(workspace)} variables)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
